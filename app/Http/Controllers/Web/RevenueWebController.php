<?php

namespace App\Http\Controllers\Web;

use App\Http\Controllers\Controller;
use App\Models\MasterOpd;
use App\Models\MasterRetribusi;
use App\Models\MasterLokasiObjek;
use App\Models\Revenue;
use Illuminate\Http\Request;

class RevenueWebController extends Controller
{
    public function index(Request $request)
    {
        $opdFilter = $request->get('opd');
        $retribusiFilter = $request->get('retribusi');
        $lokasiFilter = $request->get('lokasi');
        $yearFilter = $request->get('year', date('Y'));
        $monthFilter = $request->get('month');
        $isInstallment = $request->get('is_installment');

        $baseQuery = Revenue::query()
            ->when($opdFilter, fn($q) => $q->where('master_opd_id', $opdFilter))
            ->when($retribusiFilter, fn($q) => $q->where('master_retribusi_id', $retribusiFilter))
            ->when($lokasiFilter, fn($q) => $q->where('master_lokasi_id', $lokasiFilter))
            ->when($yearFilter, fn($q) => $q->whereYear('date', $yearFilter))
            ->when($monthFilter, fn($q) => $q->whereMonth('date', $monthFilter))
            ->when($isInstallment !== null, fn($q) => $q->where('is_installment', $isInstallment));

        // Aggregate totals across ALL filtered records (not just current page)
        $totalRevenue = (clone $baseQuery)->sum('total_revenue');
        $totalTransactions = (clone $baseQuery)->sum('total_transactions');
        $regularRevenue = (clone $baseQuery)->where('is_installment', 0)->sum('total_revenue');
        $installmentRevenue = (clone $baseQuery)->where('is_installment', 1)->sum('total_revenue');

        $data = (clone $baseQuery)
            ->with(['opd', 'retribusi', 'lokasi', 'rincianRetribusi', 'subRincianRetribusi', 'objek'])
            ->orderBy('date', 'desc')
            ->paginate(20);

        $opds = MasterOpd::orderBy('nama_opd')->get();
        $retribusis = MasterRetribusi::orderBy('nama_retribusi')->get();
        $lokasis = MasterLokasiObjek::orderBy('nama_lokasi')->get();
        $years = range(date('Y'), date('Y') - 5);
        $months = [
            1 => 'Januari',
            2 => 'Februari',
            3 => 'Maret',
            4 => 'April',
            5 => 'Mei',
            6 => 'Juni',
            7 => 'Juli',
            8 => 'Agustus',
            9 => 'September',
            10 => 'Oktober',
            11 => 'November',
            12 => 'Desember'
        ];

        return view('revenue.index', compact(
            'data',
            'opds',
            'retribusis',
            'lokasis',
            'years',
            'months',
            'opdFilter',
            'retribusiFilter',
            'lokasiFilter',
            'yearFilter',
            'monthFilter',
            'isInstallment',
            'totalRevenue',
            'totalTransactions',
            'regularRevenue',
            'installmentRevenue'
        ));
    }

    // Create and Store methods removed - revenues are auto-generated by cron job

    public function show($id)
    {
        $data = Revenue::with(['opd', 'retribusi', 'lokasi', 'rincianRetribusi', 'subRincianRetribusi', 'objek'])->findOrFail($id);
        return view('revenue.show', compact('data'));
    }

    // Edit, Update, and Delete methods removed - revenues are auto-generated by cron job
    // Data should not be manually modified to maintain integrity
}
